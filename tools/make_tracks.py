"""Builds firmware/include/tracks.h: small outline bitmaps of MotoGP and F1 circuits.

MotoGP outlines come from the MotoGP calendar API, F1 outlines from
github.com/bacinger/f1-circuits (MIT licence).
"""

import io
import json
import math
import sys
import urllib.request
from datetime import date
from pathlib import Path

from PIL import Image, ImageDraw, ImageFilter

W, H = 72, 54
OUT = Path(__file__).resolve().parent.parent / "firmware" / "include" / "tracks.h"
MOTOGP_EVENTS = "https://api.motogp.pulselive.com/motogp/v1/events?seasonYear={}"
F1_GEOJSON = "https://raw.githubusercontent.com/bacinger/f1-circuits/master/f1-circuits.geojson"


def fetch(url):
    with urllib.request.urlopen(urllib.request.Request(url, headers={"User-Agent": "TimeBuddy"}), timeout=60) as r:
        return r.read()


def fit(img):
    bbox = img.getbbox()
    if not bbox:
        return None
    img = img.crop(bbox)
    scale = min(W / img.width, H / img.height)
    block = max(1, int(1 / scale))
    if block > 1:
        img = img.filter(ImageFilter.MaxFilter(block | 1))
    w, h = max(1, round(img.width * scale)), max(1, round(img.height * scale))
    small = img.resize((w, h), Image.Resampling.NEAREST)
    out = Image.new("L", (W, H), 0)
    out.paste(small, ((W - w) // 2, (H - h) // 2))
    return out


def motogp_outline(url):
    img = Image.open(io.BytesIO(fetch(url))).convert("RGBA")
    alpha = img.getchannel("A").point(lambda a: 255 if a > 100 else 0)
    return fit(alpha)


def f1_outline(coords):
    lat0 = sum(c[1] for c in coords) / len(coords)
    k = math.cos(math.radians(lat0))
    pts = [(lon * k, -lat) for lon, lat in coords]
    xs, ys = [p[0] for p in pts], [p[1] for p in pts]
    span = max(max(xs) - min(xs), max(ys) - min(ys))
    big = 800
    pts = [((x - min(xs)) / span * (big - 20) + 10, (y - min(ys)) / span * (big - 20) + 10) for x, y in pts]
    img = Image.new("L", (big, big), 0)
    ImageDraw.Draw(img).line(pts + [pts[0]], fill=255, width=22)
    return fit(img)


def to_bytes(img):
    data = []
    for y in range(H):
        for xb in range(0, W, 8):
            byte = 0
            for bit in range(8):
                x = xb + bit
                if x < W and img.getpixel((x, y)):
                    byte |= 0x80 >> bit
            data.append(byte)
    return data


def main():
    tracks = []
    seen = set()
    year = date.today().year
    for y in (year, year + 1):
        try:
            events = json.loads(fetch(MOTOGP_EVENTS.format(y)))
        except Exception as e:
            print(f"MotoGP {y}: {e}", file=sys.stderr)
            continue
        for e in events:
            c = e.get("circuit") or {}
            if not c.get("id") or c["id"] in seen:
                continue
            simple = next((t.get("assets", {}).get("simple") for t in c.get("tracks") or [] if t.get("assets", {}).get("simple")), None)
            if not simple:
                continue
            img = motogp_outline(simple["path"])
            if img:
                seen.add(c["id"])
                tracks.append((c["name"], float(c["lat"]), float(c["lng"]), img))

    for f in json.loads(fetch(F1_GEOJSON))["features"]:
        coords = f["geometry"]["coordinates"]
        lat = sum(c[1] for c in coords) / len(coords)
        lon = sum(c[0] for c in coords) / len(coords)
        tracks.append((f["properties"]["Name"], lat, lon, f1_outline(coords)))

    lines = [
        "#pragma once",
        "",
        "#include <Arduino.h>",
        "",
        "// Generated by tools/make_tracks.py",
        "",
        f"static const int TRACK_W = {W};",
        f"static const int TRACK_H = {H};",
        "",
        "struct Track {",
        "  float lat;",
        "  float lon;",
        "  const uint8_t *bits;",
        "};",
        "",
    ]
    for i, (name, _, _, img) in enumerate(tracks):
        data = to_bytes(img)
        lines.append(f"// {name}")
        lines.append(f"static const uint8_t TRACK_{i}[] PROGMEM = {{")
        for j in range(0, len(data), 18):
            lines.append("    " + ", ".join(f"0x{b:02x}" for b in data[j:j + 18]) + ",")
        lines.append("};")
    lines.append("")
    lines.append("static const Track TRACKS[] = {")
    for i, (name, lat, lon, _) in enumerate(tracks):
        lines.append(f"    {{{lat:.4f}f, {lon:.4f}f, TRACK_{i}}},")
    lines.append("};")
    lines.append("")
    OUT.write_text("\n".join(lines))
    print(f"{len(tracks)} tracks -> {OUT}")


if __name__ == "__main__":
    main()
