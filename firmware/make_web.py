"""Builds include/web.h: the gzipped setup page and time zone table, served by the device.

Runs before each PlatformIO build. Time zones come from github.com/nayarsystems/posix_tz_db (MIT licence).
"""

import gzip
from pathlib import Path

Import("env")  # noqa: F821

ROOT = Path(env.subst("$PROJECT_DIR"))  # noqa: F821
FILES = [("index.html", "WEB_INDEX"), ("zones.json", "WEB_ZONES")]

lines = ["#pragma once", "", "#include <Arduino.h>", "", "// Generated by make_web.py", ""]
for name, symbol in FILES:
    data = gzip.compress((ROOT / "web" / name).read_bytes(), 9, mtime=0)
    lines.append(f"static const uint8_t {symbol}[] PROGMEM = {{")
    for i in range(0, len(data), 18):
        lines.append("    " + ", ".join(f"0x{b:02x}" for b in data[i : i + 18]) + ",")
    lines.append("};")
    lines.append(f"static const size_t {symbol}_LEN = {len(data)};")
    lines.append("")

out = ROOT / "include" / "web.h"
text = "\n".join(lines)
if not out.exists() or out.read_text() != text:
    out.write_text(text)
